# ===== 组装 =====
def ep(n, scene, chars, beats, card, hook):
    return n, scene, chars, beats, card, hook

def emit(n, scene, chars, beats, card, hook):
    d = sum(1 for b in beats if b[0] == 'd')
    a = sum(1 for b in beats if b[0] == 'a')
    assert d == 14 and a == 8, f"!! E{n} 结构错: d={d} a={a} (须14/8)"
    out = [f"## 第{n}集", "", scene, chars, ""]
    for b in beats:
        if b[0] == 'd':
            # 对白 beat: 只出对白行(动作写在括号内)，不另插△行
            out.append(f"**{b[1]}**（{b[2]}）：\"{b[3]}\"")
        else:
            # 动作 beat: △行
            out.append(f"△{b[1]}。")
    out += ["", card, "", hook, "", f"——第{n}集完——", ""]
    return "\n".join(out)

def main():
    lo = int(sys.argv[1]); hi = int(sys.argv[2]); out = sys.argv[3]
    blocks = []
    for n in range(lo, hi+1):
        assert n in EPS, f"!! 缺 E{n} 数据"
        blocks.append(emit(n, *EPS[n]))
    open(out, 'w', encoding='utf-8').write("\n".join(blocks))
    print(f"已生成 E{lo}-{hi} → {out} (共 {hi-lo+1} 集)")

if __name__ == '__main__':
    main()
